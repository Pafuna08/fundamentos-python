numero_1 = 10
numero_2 = 3

print("Numero 1:", numero_1)
print("Numero 2:", numero_2)
print("Suma:", numero_1 + numero_2)
print("Resta:", numero_1 - numero_2)
print("Multiplicacion:", numero_1 * numero_2)
print("Division:", numero_1 / numero_2)
print("Division entera:", numero_1 // numero_2)
print("Modulo:", numero_1 % numero_2)
print("Potencia:", numero_1 ** numero_2)

print(f"{numero_1} es mayor que {numero_2}:", numero_1 > numero_2)
print(f"{numero_1} es menor que {numero_2}:", numero_1 < numero_2)
print(f"{numero_1} es igual a {numero_2}:", numero_1 == numero_2)
print(f"{numero_1} es diferente de {numero_2}:", numero_1 != numero_2)
